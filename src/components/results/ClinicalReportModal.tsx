import React from 'react';
import { Modal } from '../ui/Modal';
import { Button } from '../ui/Button';
import { Badge } from '../ui/Badge';
import { Download, Printer, ShieldAlert, Check } from 'lucide-react';
import { AnalysisResult } from '../../types';
import { METAVIR_STAGES } from '../../data/clinicalConstants';

interface ClinicalReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  result: AnalysisResult | null;
}

export const ClinicalReportModal: React.FC<ClinicalReportModalProps> = ({
  isOpen,
  onClose,
  result,
}) => {
  const [downloadSuccess, setDownloadSuccess] = React.useState(false);

  if (!result) return null;

  const stageMeta = METAVIR_STAGES[result.predictedStage] || METAVIR_STAGES.F2;

  const handleDownload = () => {
    const reportData = {
      project: 'LiverFusion AI Research Platform',
      title: 'Multimodal Deep Fusion Networks for Automated Detection and Staging of Liver Cirrhosis',
      disclaimer: 'RESEARCH PROTOTYPE ONLY. NOT INTENDED FOR CLINICAL DIAGNOSIS.',
      reportGeneratedAt: new Date().toISOString(),
      scanMetadata: {
        analysisId: result.id,
        filename: result.fileName,
        fileSize: result.fileSizeFormatted,
        modality: result.modality,
        modelTopology: result.model,
      },
      assessmentPlaceholder: {
        stage: stageMeta.stage,
        stageName: stageMeta.name,
        confidence: `${(result.top1Confidence * 100).toFixed(1)}%`,
        isDemonstrationData: true,
        histologyCriterion: stageMeta.histologyCriterion,
        clinicalSignificance: stageMeta.clinicalSignificance,
      },
    };

    const blob = new Blob([JSON.stringify(reportData, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `LiverFusion_Report_${result.id}_DEMO.json`;
    a.click();
    URL.revokeObjectURL(url);

    setDownloadSuccess(true);
    setTimeout(() => setDownloadSuccess(false), 2500);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title="Standardized Clinical Research Report (Demo)"
      subtitle="Summary of imaging analysis, algorithmic staging & explainability"
      maxWidth="2xl"
    >
      <div className="space-y-6 text-slate-800">
        {/* Banner */}
        <div className="p-3.5 rounded-xl bg-amber-50 border border-amber-200 text-xs text-amber-900 flex items-start gap-2.5">
          <ShieldAlert className="w-5 h-5 text-amber-600 shrink-0 mt-0.5" />
          <div>
            <strong className="font-semibold uppercase tracking-wide text-[11px] block">
              Mandatory Regulatory Notice
            </strong>
            <p className="text-[11px] leading-relaxed mt-0.5 text-amber-800">
              This report layout is generated by the LiverFusion AI Phase 1 research prototype. 
              Figures and classifications displayed here represent demonstration data placeholders and 
              must <strong>never</strong> be used for patient management or medical diagnostic decisions.
            </p>
          </div>
        </div>

        {/* Report Document Header */}
        <div className="p-4 rounded-xl border border-slate-200 bg-slate-50/50 space-y-3">
          <div className="flex items-center justify-between border-b border-slate-200 pb-3">
            <div>
              <div className="font-bold text-slate-900 text-base">LiverFusion AI Staging Analysis</div>
              <div className="text-[11px] text-slate-500 font-mono">
                System: Multimodal Deep Fusion Core v0.1-proto
              </div>
            </div>
            <div className="text-right">
              <Badge variant="navy" size="sm" className="font-mono text-[10px]">
                {result.id}
              </Badge>
              <div className="text-[10px] text-slate-400 mt-1">{result.timestamp}</div>
            </div>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-3 gap-3 text-xs pt-1">
            <div>
              <span className="text-slate-400 block text-[10px]">Scan Filename</span>
              <span className="font-semibold text-slate-800 break-all">{result.fileName}</span>
            </div>
            <div>
              <span className="text-slate-400 block text-[10px]">Imaging Modality</span>
              <span className="font-semibold text-slate-800 capitalize">{result.modality} (B-Mode)</span>
            </div>
            <div>
              <span className="text-slate-400 block text-[10px]">Evaluated Model</span>
              <span className="font-semibold text-slate-800 uppercase font-mono">{result.model}</span>
            </div>
          </div>
        </div>

        {/* Staging Summary */}
        <div className={`p-4 rounded-xl border ${stageMeta.color.bg} ${stageMeta.color.border} space-y-2`}>
          <div className="flex items-center justify-between">
            <span className="text-xs font-semibold text-slate-700 uppercase tracking-wide">
              METAVIR Staging Assessment
            </span>
            <span className="text-xs font-mono font-bold text-amber-800 bg-amber-100/70 px-2 py-0.5 rounded">
              Demo Confidence: {(result.top1Confidence * 100).toFixed(1)}%
            </span>
          </div>
          <div className="flex items-baseline gap-2">
            <span className={`text-2xl font-black ${stageMeta.color.text}`}>{stageMeta.stage}</span>
            <span className="text-sm font-bold text-slate-900">{stageMeta.name}</span>
          </div>
          <p className="text-xs text-slate-600 leading-relaxed">
            {stageMeta.detailedDesc}
          </p>
        </div>

        {/* Explainability findings */}
        <div className="border border-slate-200 rounded-xl p-4 space-y-2 text-xs">
          <h5 className="font-semibold text-slate-800 text-[11px] uppercase tracking-wide">
            Automated Feature Map Findings (Grad-CAM Template)
          </h5>
          <ul className="list-disc list-inside space-y-1 text-slate-600 text-[11px]">
            <li>Acoustic speckle distribution evaluated across hepatic parenchyma.</li>
            <li>Periportal fibrous sheath boundary analyzed via residual feature layer.</li>
            <li>Global capsular edge contour verified against normal anatomical curves.</li>
          </ul>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center justify-between pt-2 border-t border-slate-100">
          <Button variant="outline" size="sm" onClick={handlePrint} className="text-xs">
            <Printer className="w-4 h-4 mr-1.5" />
            <span>Print Report</span>
          </Button>

          <div className="flex items-center gap-2">
            <Button variant="ghost" size="sm" onClick={onClose} className="text-xs">
              Close
            </Button>
            <Button
              variant="teal"
              size="sm"
              onClick={handleDownload}
              className="text-xs"
            >
              {downloadSuccess ? (
                <>
                  <Check className="w-4 h-4 mr-1.5 text-white" />
                  <span>Exported JSON</span>
                </>
              ) : (
                <>
                  <Download className="w-4 h-4 mr-1.5" />
                  <span>Export Report (JSON)</span>
                </>
              )}
            </Button>
          </div>
        </div>
      </div>
    </Modal>
  );
};
