"""
LiverFusion AI - Group-Aware Stratified Dataset Splitter
Ensures:
- Every duplicate group lies in EXACTLY ONE partition (train, val, or test).
- No identical or near-identical frames leak across partitions.
- Stratification maintains balanced class proportions across splits.
- Seeds and ratios are loaded directly from configs/data.yaml.
- Writes splits.csv and per-class counts per partition.
"""

import os
import sys
import csv
import json
import random
from collections import Counter, defaultdict
from typing import Dict, List, Set, Any
import yaml


def set_seed(seed: int = 42):
    """Set random seed for deterministic partitioning."""
    random.seed(seed)


def load_manifest(manifest_csv: str = "file_manifest.csv") -> List[Dict[str, str]]:
    """Load file manifest generated by ml/audit.py."""
    if not os.path.exists(manifest_csv):
        raise FileNotFoundError(
            f"File manifest not found at '{manifest_csv}'. Please run 'python -m ml.audit' first."
        )
    records = []
    with open(manifest_csv, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            records.append(row)
    return records


def load_config(config_path: str = "configs/data.yaml") -> Dict[str, Any]:
    """Load split configuration from YAML."""
    if not os.path.exists(config_path):
        raise FileNotFoundError(f"Config file not found at '{config_path}'.")
    with open(config_path, "r", encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    return cfg or {}


def make_splits(
    manifest_csv: str = "file_manifest.csv",
    config_path: str = "configs/data.yaml",
    output_splits_csv: str = "splits.csv"
) -> Dict[str, Any]:
    """
    Perform group-aware stratified split.
    Guarantees: each duplicate group lies in exactly one partition.
    """
    records = load_manifest(manifest_csv)
    cfg = load_config(config_path)

    seed = cfg.get("seed", 42)
    set_seed(seed)

    split_ratios = cfg.get("split_ratios", {"train": 0.70, "val": 0.15, "test": 0.15})
    r_train = float(split_ratios.get("train", 0.70))
    r_val = float(split_ratios.get("val", 0.15))
    r_test = float(split_ratios.get("test", 0.15))

    # Normalize ratios if necessary
    total_r = r_train + r_val + r_test
    r_train, r_val, r_test = r_train / total_r, r_val / total_r, r_test / total_r

    # Map each duplicate group to its member records
    group_to_records = defaultdict(list)
    for rec in records:
        group_to_records[rec["duplicate_group_id"]].append(rec)

    # Determine primary class for each duplicate group (by majority vote)
    group_primary_class = {}
    for gid, group_recs in group_to_records.items():
        class_counts = Counter(r["class_name"] for r in group_recs)
        primary_cls = class_counts.most_common(1)[0][0]
        group_primary_class[gid] = primary_cls

    # Cluster duplicate groups by primary class for stratified assignment
    class_to_groups = defaultdict(list)
    for gid, cls in group_primary_class.items():
        class_to_groups[cls].append(gid)

    # Deterministically shuffle groups within each class using seed
    rng = random.Random(seed)
    for cls in class_to_groups:
        # Sort first for cross-platform determinism before shuffle
        class_to_groups[cls].sort()
        rng.shuffle(class_to_groups[cls])

    # Allocate groups for each class using stratified greedy balancing
    # to achieve target sample counts while strictly keeping each group in exactly one split
    group_split_assignment: Dict[str, str] = {}

    for cls, groups in sorted(class_to_groups.items()):
        total_cls_samples = sum(len(group_to_records[g]) for g in groups)
        target_train = total_cls_samples * r_train
        target_val = total_cls_samples * r_val
        target_test = total_cls_samples * r_test

        cls_counts = {"train": 0, "val": 0, "test": 0}

        # Sort groups by size descending to pack larger groups first
        groups_sorted = sorted(groups, key=lambda g: (-len(group_to_records[g]), g))

        for gid in groups_sorted:
            group_sz = len(group_to_records[gid])
            # Determine which partition has the greatest deficit relative to target
            deficits = {
                "train": (target_train - cls_counts["train"]) / max(target_train, 1),
                "val": (target_val - cls_counts["val"]) / max(target_val, 1),
                "test": (target_test - cls_counts["test"]) / max(target_test, 1),
            }
            # Best partition is the one with highest deficit
            best_split = max(deficits.keys(), key=lambda s: deficits[s])
            group_split_assignment[gid] = best_split
            cls_counts[best_split] += len(group_to_records[gid])

    # Assign split to each individual file record
    for rec in records:
        rec["split"] = group_split_assignment[rec["duplicate_group_id"]]

    # Run strict verification check: No group spans two partitions!
    group_partitions: Dict[str, Set[str]] = defaultdict(set)
    for rec in records:
        group_partitions[rec["duplicate_group_id"]].add(rec["split"])

    spanning_groups = {
        gid: splits for gid, splits in group_partitions.items() if len(splits) > 1
    }
    if spanning_groups:
        raise AssertionError(
            f"Integrity Violation: {len(spanning_groups)} duplicate groups span multiple partitions: {spanning_groups}"
        )

    # Compute partition counts
    partition_counts = Counter(rec["split"] for rec in records)
    per_class_partition_counts = defaultdict(Counter)
    for rec in records:
        per_class_partition_counts[rec["split"]][rec["class_name"]] += 1

    # Write splits.csv
    fieldnames = [
        "relative_path",
        "class_name",
        "duplicate_group_id",
        "split",
        "filename",
        "size_bytes",
        "mode",
        "dimensions",
        "md5"
    ]
    with open(output_splits_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        for rec in records:
            writer.writerow(rec)

    summary = {
        "seed": seed,
        "split_ratios_target": {"train": r_train, "val": r_val, "test": r_test},
        "total_images": len(records),
        "total_duplicate_groups": len(group_to_records),
        "partition_counts": dict(partition_counts),
        "per_class_partition_counts": {k: dict(v) for k, v in per_class_partition_counts.items()},
        "spanning_groups_count": len(spanning_groups),
        "integrity_check": "PASSED: No duplicate group spans two partitions."
    }

    return summary


def verify_splits_file(splits_csv: str = "splits.csv") -> bool:
    """
    Re-runnable verification check:
    Verifies that no duplicate_group_id appears in more than one partition.
    """
    if not os.path.exists(splits_csv):
        print(f"Error: {splits_csv} does not exist.")
        return False

    group_to_splits = defaultdict(set)
    total_rows = 0
    with open(splits_csv, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            total_rows += 1
            group_to_splits[row["duplicate_group_id"]].add(row["split"])

    spanning = {gid: s for gid, s in group_to_splits.items() if len(s) > 1}
    if spanning:
        print(f"FAIL: {len(spanning)} duplicate groups span across multiple splits: {spanning}")
        return False
    else:
        print(f"VERIFIED: 0 of {len(group_to_splits)} duplicate groups span multiple splits.")
        print(f"Total files verified: {total_rows}")
        return True


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Group-aware dataset splitter")
    parser.add_argument("--manifest", default="file_manifest.csv", help="Input file manifest CSV")
    parser.add_argument("--config", default="configs/data.yaml", help="Path to config YAML")
    parser.add_argument("--out", default="splits.csv", help="Output splits CSV")
    parser.add_argument("--verify", action="store_true", help="Run verification check on existing splits.csv")
    args = parser.parse_args()

    if args.verify:
        passed = verify_splits_file(args.out)
        sys.exit(0 if passed else 1)

    print("Executing group-aware stratified split...")
    summary = make_splits(args.manifest, args.config, args.out)

    print("\n=== Split Summary ===")
    print(f"Total Images: {summary['total_images']}")
    print(f"Total Duplicate Groups: {summary['total_duplicate_groups']}")
    print(f"Partition Sample Counts: {summary['partition_counts']}")
    print("\nPer-Class Counts per Partition:")
    for partition in ["train", "val", "test"]:
        counts = summary["per_class_partition_counts"].get(partition, {})
        total_p = sum(counts.values())
        print(f"  {partition.upper()} ({total_p} images): {counts}")
    print(f"\nIntegrity Check: {summary['integrity_check']}")
    print(f"Wrote splits to: {args.out}")
